import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';

const previewPath='C:/Users/Bilal/.codex/visualizations/2026/10/10/01a1278f-c316-7e23-a3dc-889381d01979/painting-rate-scenario.html';
const fragment=fs.readFileSync(previewPath,'utf8');
const js=fragment.match(/<script>([\s\S]*?)<\/script>/)[1];
const ast=ts.createSourceFile('scenario.js',js,ts.ScriptTarget.Latest,true,ts.ScriptKind.JS);
let fn;
function visit(node){if(ts.isFunctionDeclaration(node)&&node.name?.text==='calculate')fn=node.getText(ast);ts.forEachChild(node,visit);}
visit(ast);
assert.ok(fn,'Scenario calculation function exists');
const calculate=new Function(fn+'; return calculate;')();
const base={labor:{standard:35,good:40,premium:50},material:{standard:8,good:14,premium:22},putty:6,primer:4,door:800,window:500,texture:45};
const state={length:12,width:10,height:10,quality:'good',location:1.6,coats:2,ceiling:true,paint:true,putty:true,primer:true,roof:true,woodwork:false,doors:0,windows:0,textureWalls:0,coverage:100,wastage:10,packSize:4,materialMode:'area',packPrice:0,scaffolding:0,minimum:0};
const run=change=>calculate({...state,...change},base);
const close=(actual,expected)=>assert.ok(Math.abs(actual-expected)<1e-6,`${actual} should equal ${expected}`);
close(run({wastage:0,roof:false}).total,86374.4*1.2);
close(run({wastage:0}).total,86374.4*1.2*1.05);
close(run({}).total,111360.6144);
close(run({}).oldTotal,86374.4);
assert.equal(run({doors:1,windows:1}).area,560);
assert.equal(run({woodwork:true,doors:1,windows:1}).area,527);
close(run({woodwork:true,doors:1,windows:1}).doors,800*1.2*1.6);
close(run({woodwork:true,doors:1,windows:1}).windows,500*1.2*1.6);
close(run({textureWalls:1}).texture,110*45*1.2*1.6);
const packs=run({materialMode:'packs',packPrice:4000});
close(packs.rawLitres,11.2);close(packs.wasteLitres,1.12);assert.equal(packs.packs,4);
assert.equal(packs.material,12000);assert.equal(packs.wasteCost,4000);
assert.equal(run({materialMode:'packs',paint:false}).material,0);
assert.equal(run({paint:false}).requiredLitres,0);
assert.equal(run({paint:false}).wasteCost,0);
close(run({scaffolding:2500}).total,run({}).total+2500);
assert.equal(run({minimum:150000}).total,150000);
close(run({minimum:150000}).minimumTopUp,150000-run({}).total);
close(run({minimum:1000}).minimumTopUp,0);
assert.throws(()=>run({length:-2}));assert.throws(()=>run({doors:0.5}));assert.throws(()=>run({materialMode:'packs'}));
assert.throws(()=>run({woodwork:true,doors:100}));assert.throws(()=>run({coverage:0}));
assert.throws(()=>run({quality:'unknown'}));assert.throws(()=>run({wastage:101}));
for(const name of ['length','width','height','quality','location','coats','ceiling','paint','putty','primer','roof','woodwork','doors','windows','textureWalls','coverage','wastage','packSize','materialMode','packPrice','scaffolding','minimum'])assert.ok(fragment.includes(`name="${name}"`));
fs.writeFileSync('GSC_analyses/scenario-check-results.json',JSON.stringify({date:'2026-10-12',defaultScenario:state,defaultResult:run({}),roofOnlyResult:run({wastage:0}),quantityPricingExample:{packPrice:4000,...packs},status:'All scenario checks passed'},null,2)+'\n');
console.log('Scenario checks passed: rate uplift, roof, openings, quantity pricing, no double charges, scaffolding, minimum, validation and control bindings.');
